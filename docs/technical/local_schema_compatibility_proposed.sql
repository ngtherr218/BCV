ALTER TABLE app_user ADD COLUMN last_login_at timestamptz;
ALTER TABLE app_user ADD COLUMN media_upload_blocked boolean NOT NULL DEFAULT false;
ALTER TABLE user_card ADD COLUMN seen_at timestamptz;
ALTER TABLE notification ADD COLUMN hidden_at timestamptz;
ALTER TABLE place ADD COLUMN feature_source varchar(10) NOT NULL DEFAULT 'CUSTOM' CHECK(feature_source IN ('TYPE','CUSTOM'));
ALTER TABLE recommendation_config ADD COLUMN settings jsonb NOT NULL;
CREATE TABLE interest_group (
 interest_group_id bigint PRIMARY KEY, code varchar(50) NOT NULL UNIQUE, name varchar(100) NOT NULL
);
CREATE TABLE user_preference_interest (
 user_preference_id bigint NOT NULL REFERENCES user_preference(user_preference_id) ON DELETE CASCADE ON UPDATE NO ACTION,
 interest_group_id bigint NOT NULL REFERENCES interest_group(interest_group_id) ON DELETE NO ACTION ON UPDATE NO ACTION,
 PRIMARY KEY(user_preference_id,interest_group_id)
);
CREATE TABLE recommendation_rating_snapshot (
 recommendation_config_id bigint NOT NULL REFERENCES recommendation_config ON DELETE NO ACTION ON UPDATE NO ACTION,
 place_id bigint NOT NULL REFERENCES place ON DELETE NO ACTION ON UPDATE NO ACTION,
 rating numeric(3,2), rating_count integer,
 PRIMARY KEY(recommendation_config_id,place_id),
 CHECK(rating IS NULL OR rating BETWEEN 0 AND 5), CHECK(rating_count IS NULL OR rating_count>=0)
);
CREATE UNIQUE INDEX one_active_recommendation_config ON recommendation_config ((status)) WHERE status='ACTIVE';
CREATE TABLE place_type_feature (
 place_type_id bigint NOT NULL REFERENCES place_type ON DELETE CASCADE ON UPDATE NO ACTION,
 code varchar(50) NOT NULL, PRIMARY KEY(place_type_id,code)
);
CREATE TABLE community_media (
 media_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES app_user ON DELETE NO ACTION ON UPDATE NO ACTION,
 place_id bigint NOT NULL REFERENCES place ON DELETE NO ACTION ON UPDATE NO ACTION,
 caption varchar(500) NOT NULL DEFAULT '', mime_type varchar(40) NOT NULL,
 media_data bytea,
 status varchar(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','APPROVED','REJECTED','FLAGGED','REMOVED','EXPIRED')),
 review_note varchar(500), reviewed_by bigint REFERENCES app_user ON DELETE NO ACTION ON UPDATE NO ACTION,
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, reviewed_at timestamptz,
 first_approved_at timestamptz, file_deleted_at timestamptz, delete_after timestamptz
);
CREATE INDEX community_media_place_status_idx ON community_media(place_id,status);
CREATE INDEX community_media_review_idx ON community_media(status,created_at);
CREATE TABLE media_report (
 report_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 media_id bigint NOT NULL REFERENCES community_media ON DELETE CASCADE ON UPDATE NO ACTION,
 reporter_id bigint NOT NULL REFERENCES app_user ON DELETE NO ACTION ON UPDATE NO ACTION,
 reason varchar(500) NOT NULL CHECK(length(trim(reason))>0),
 status varchar(12) NOT NULL DEFAULT 'OPEN' CHECK(status IN ('OPEN','RESOLVED','ACCEPTED','DISMISSED')),
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 resolved_at timestamptz, resolved_by bigint REFERENCES app_user ON DELETE NO ACTION ON UPDATE NO ACTION,
 UNIQUE(media_id,reporter_id)
);
CREATE INDEX media_report_open_idx ON media_report(media_id,status);
CREATE TABLE place_video (
 video_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 place_id bigint REFERENCES place ON DELETE NO ACTION ON UPDATE NO ACTION,
 created_by bigint NOT NULL REFERENCES app_user ON DELETE NO ACTION ON UPDATE NO ACTION,
 mime_type varchar(40) NOT NULL DEFAULT 'video/mp4', video_data bytea NOT NULL,
 duration_seconds double precision NOT NULL CHECK(duration_seconds>0 AND duration_seconds<=60),
 width integer NOT NULL CHECK(width>0), height integer NOT NULL CHECK(height>0),
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX place_video_place_idx ON place_video(place_id);
COMMIT;
