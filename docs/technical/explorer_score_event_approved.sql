BEGIN;
DO $$ BEGIN
  IF current_database() <> 'vietnam_explorer_dev_v2' THEN
    RAISE EXCEPTION 'Wrong database';
  END IF;
END $$;
CREATE TABLE explorer_score_event (
  score_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  event_type VARCHAR(30) NOT NULL CHECK(event_type IN ('FIRST_PLACE','JOURNEY','QUEST')),
  source_key VARCHAR(100) NOT NULL,
  place_id BIGINT REFERENCES place(place_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  region_id BIGINT REFERENCES region(region_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  points INTEGER NOT NULL CHECK(points>0),
  rule_version VARCHAR(30) NOT NULL,
  occurred_at TIMESTAMPTZ NOT NULL,
  UNIQUE(user_id,event_type,source_key)
);
CREATE INDEX explorer_score_time_user_idx ON explorer_score_event(occurred_at,user_id);
CREATE INDEX explorer_score_region_time_user_idx ON explorer_score_event(region_id,occurred_at,user_id);
COMMIT;
