CREATE TABLE IF NOT EXISTS daily_activity (
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    activity_date DATE NOT NULL,
    steps INTEGER NOT NULL CHECK (steps BETWEEN 0 AND 40000),
    goal_steps INTEGER NOT NULL CHECK (goal_steps > 0),
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, activity_date)
);
CREATE INDEX IF NOT EXISTS daily_activity_date_idx ON daily_activity(activity_date);
-- Two sources for the same day: Health Connect's daily total and the steps synced into journeys
-- (device sensor, test steps). steps = the larger one, so neither source is counted twice.
ALTER TABLE daily_activity ADD COLUMN IF NOT EXISTS health_steps INTEGER NOT NULL DEFAULT 0;
ALTER TABLE daily_activity ADD COLUMN IF NOT EXISTS journey_steps INTEGER NOT NULL DEFAULT 0;
-- Rows written before the split only had Health Connect totals.
UPDATE daily_activity SET health_steps = steps WHERE health_steps = 0 AND journey_steps = 0 AND steps > 0;

-- F80: rest days keep the streak (at most 7 days per pause, one pause at a time).
CREATE TABLE IF NOT EXISTS activity_pause (
    pause_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (end_date >= start_date AND end_date - start_date < 7)
);
CREATE INDEX IF NOT EXISTS activity_pause_user_idx ON activity_pause(user_id, end_date);

CREATE TABLE IF NOT EXISTS journal_photo (
    photo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    place_id BIGINT NOT NULL REFERENCES place(place_id) ON DELETE CASCADE,
    caption VARCHAR(300) NOT NULL DEFAULT '',
    mime_type VARCHAR(20) NOT NULL CHECK (mime_type IN ('image/jpeg','image/png','image/webp')),
    photo_data BYTEA NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS journal_photo_owner_idx ON journal_photo(user_id, place_id);
CREATE TABLE IF NOT EXISTS journal_note (
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    place_id BIGINT NOT NULL REFERENCES place(place_id) ON DELETE CASCADE,
    note VARCHAR(1000) NOT NULL DEFAULT '',
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, place_id)
);
