-- F76 question bank: curated multiple-choice questions per place, managed by administrators.
-- Only ACTIVE questions reach the app; SAMPLE rows come from db/028_seed_place_questions.sql.
CREATE TABLE IF NOT EXISTS place_question (
    question_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id BIGINT NOT NULL REFERENCES place(place_id) ON DELETE CASCADE,
    question VARCHAR(300) NOT NULL,
    option_a VARCHAR(150) NOT NULL,
    option_b VARCHAR(150) NOT NULL,
    option_c VARCHAR(150) NOT NULL,
    option_d VARCHAR(150) NOT NULL,
    -- 0 = A … 3 = D
    answer_index SMALLINT NOT NULL CHECK (answer_index BETWEEN 0 AND 3),
    explanation VARCHAR(400) NOT NULL DEFAULT '',
    difficulty SMALLINT NOT NULL DEFAULT 1 CHECK (difficulty BETWEEN 1 AND 3),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'ACTIVE', 'INACTIVE')),
    source VARCHAR(20) NOT NULL DEFAULT 'ADMIN' CHECK (source IN ('ADMIN', 'SAMPLE')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (place_id, question)
);
CREATE INDEX IF NOT EXISTS place_question_place_idx ON place_question(place_id, status);

-- Quiz rewards keep walking the only way forward: no steps are given. A correct answer earns
-- explorer points, a card piece and quest progress; all stops of a journey correct = "Am hiểu" card.
CREATE TABLE IF NOT EXISTS user_place_mastery (
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    place_id BIGINT NOT NULL REFERENCES place(place_id) ON DELETE CASCADE,
    mastered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, place_id)
);
