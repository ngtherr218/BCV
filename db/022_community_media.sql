CREATE TABLE IF NOT EXISTS public.community_media (
 media_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES public.app_user(user_id),
 place_id BIGINT NOT NULL REFERENCES public.place(place_id),
 caption VARCHAR(500) NOT NULL DEFAULT '', mime_type VARCHAR(40) NOT NULL,
 media_data BYTEA NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','APPROVED','REJECTED')),
 review_note VARCHAR(500), reviewed_by BIGINT REFERENCES public.app_user(user_id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, reviewed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS community_media_place_status_idx ON public.community_media(place_id,status);
CREATE INDEX IF NOT EXISTS community_media_review_idx ON public.community_media(status,created_at);
