-- Badges, managed on the admin web (Trò chơi hóa › Huy hiệu). condition_type names a metric the
-- server already computes per user; a badge is earned once that metric reaches target_value.
CREATE TABLE IF NOT EXISTS badge (
    badge_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(300) NOT NULL,
    condition_type VARCHAR(30) NOT NULL CHECK (condition_type IN
        ('PLACES_DISCOVERED','ZONES_TOUCHED','ZONES_COMPLETED','BEST_STREAK','REAL_CHECKINS',
         'PROVINCES_STAMPED','QUIZ_CORRECT','CARDS_MASTERED')),
    target_value INT NOT NULL CHECK (target_value >= 1),
    sort_order INT NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('DRAFT','ACTIVE','INACTIVE'))
);
