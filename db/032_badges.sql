-- Badge art: an uploaded image (badges/ folder, or an https URL) like card art. The emoji icon used
-- before images is gone.
ALTER TABLE badge ADD COLUMN IF NOT EXISTS image_key TEXT;
ALTER TABLE badge DROP COLUMN IF EXISTS icon;

-- Badge codes are internal: a badge added on the admin web gets BADGE_{id} automatically.
CREATE OR REPLACE FUNCTION badge_default_code() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.code IS NULL OR btrim(NEW.code) = '' THEN NEW.code := 'BADGE_' || NEW.badge_id; END IF;
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS badge_default_code ON badge;
CREATE TRIGGER badge_default_code BEFORE INSERT ON badge FOR EACH ROW EXECUTE FUNCTION badge_default_code();
