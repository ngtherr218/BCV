CREATE TABLE IF NOT EXISTS place_video (
 video_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 place_id bigint REFERENCES place,
 created_by bigint NOT NULL REFERENCES app_user,
 mime_type varchar(40) NOT NULL DEFAULT 'video/mp4',
 video_data bytea NOT NULL,
 duration_seconds double precision NOT NULL CHECK(duration_seconds>0 AND duration_seconds<=30),
 width integer NOT NULL CHECK(width>0),height integer NOT NULL CHECK(height>0),
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS place_video_place_idx ON place_video(place_id);
