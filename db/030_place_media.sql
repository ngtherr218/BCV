-- One table for a place's official media: photos and videos (admin-managed), replacing place_image
-- and place_video. A photo keeps its image_key (https URL or inline data URI); a video keeps its MP4
-- bytes and size. Videos keep their ids (they are in /videos/{id} URLs); photos keep their order.
-- A video may be uploaded before it is attached, so place_id is NULL for a while (cleaned after 24 h).
-- Re-runnable: copies only while the old tables exist, then drops them.
CREATE TABLE IF NOT EXISTS place_media (
    media_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id BIGINT REFERENCES place(place_id),
    media_type VARCHAR(10) NOT NULL CHECK (media_type IN ('IMAGE', 'VIDEO')),
    image_key TEXT,
    video_data BYTEA,
    mime_type VARCHAR(40),
    duration_seconds DOUBLE PRECISION,
    width INTEGER,
    height INTEGER,
    created_by BIGINT REFERENCES app_user(user_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (media_type <> 'IMAGE' OR (image_key IS NOT NULL AND place_id IS NOT NULL)),
    CHECK (media_type <> 'VIDEO' OR (video_data IS NOT NULL AND duration_seconds > 0 AND duration_seconds <= 60
                                     AND width > 0 AND height > 0))
);
CREATE INDEX IF NOT EXISTS place_media_place_idx ON place_media(place_id, media_type, media_id);

DO $$
BEGIN
    IF to_regclass('place_video') IS NOT NULL THEN
        INSERT INTO place_media (media_id, place_id, media_type, video_data, mime_type, duration_seconds, width, height, created_by, created_at)
        SELECT video_id, place_id, 'VIDEO', video_data, mime_type, duration_seconds, width, height, created_by, created_at
        FROM place_video ORDER BY video_id
        ON CONFLICT (media_id) DO NOTHING;
        DROP TABLE place_video;
    END IF;
    IF to_regclass('place_image') IS NOT NULL THEN
        -- photos get fresh ids after every existing one, in their old order
        PERFORM setval(pg_get_serial_sequence('place_media', 'media_id'),
                       GREATEST((SELECT COALESCE(max(media_id), 0) FROM place_media), 1));
        INSERT INTO place_media (place_id, media_type, image_key)
        SELECT place_id, 'IMAGE', image_key FROM place_image ORDER BY place_image_id;
        DROP TABLE place_image;
    END IF;
    PERFORM setval(pg_get_serial_sequence('place_media', 'media_id'),
                   GREATEST((SELECT COALESCE(max(media_id), 0) FROM place_media), 1));
END $$;
