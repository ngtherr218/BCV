-- Engagement features (re-runnable): flexible destination choice, steps as "fuel",
-- streaks/passport/leaderboard, private journal instead of moderated community uploads,
-- and server-side step plausibility checks.
-- F74 "Không quan tâm": hide a place from recommendations for 30 days.
CREATE TABLE IF NOT EXISTS place_dismissal (
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    place_id BIGINT NOT NULL REFERENCES place(place_id) ON DELETE CASCADE,
    dismissed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, place_id)
);

-- F83/F85: one row per user per local day; goal is the personal daily goal on that day.
CREATE TABLE IF NOT EXISTS daily_activity (
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    activity_date DATE NOT NULL,
    steps INTEGER NOT NULL CHECK (steps BETWEEN 0 AND 40000),
    goal_steps INTEGER NOT NULL CHECK (goal_steps > 0),
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, activity_date)
);
CREATE INDEX IF NOT EXISTS daily_activity_date_idx ON daily_activity(activity_date);
-- Two sources for the same day: Health Connect's daily total and the steps synced into journeys
-- (device sensor, test steps). steps = the larger one, so neither source is counted twice.
ALTER TABLE daily_activity ADD COLUMN IF NOT EXISTS health_steps INTEGER NOT NULL DEFAULT 0;
ALTER TABLE daily_activity ADD COLUMN IF NOT EXISTS journey_steps INTEGER NOT NULL DEFAULT 0;
-- Rows written before the split only had Health Connect totals.
UPDATE daily_activity SET health_steps = steps WHERE health_steps = 0 AND journey_steps = 0 AND steps > 0;

-- F80 rest days were dropped: a streak is only kept by reaching the daily goal.
DROP TABLE IF EXISTS activity_pause;

-- F77: being physically at a place (GPS) unlocks it with a "real visit" stamp.
CREATE TABLE IF NOT EXISTS place_checkin (
    checkin_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    place_id BIGINT NOT NULL REFERENCES place(place_id) ON DELETE CASCADE,
    checkin_date DATE NOT NULL,
    latitude NUMERIC(9,6) NOT NULL,
    longitude NUMERIC(9,6) NOT NULL,
    distance_meters INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, place_id, checkin_date)
);

-- F76: culture questions add bonus distance to the active journey (capped at 20 %).
ALTER TABLE journey ADD COLUMN IF NOT EXISTS bonus_steps INTEGER NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS journey_quiz_answer (
    journey_id BIGINT NOT NULL REFERENCES journey(journey_id) ON DELETE CASCADE,
    question_key VARCHAR(60) NOT NULL,
    answered_on DATE NOT NULL,
    is_correct BOOLEAN NOT NULL,
    bonus_steps INTEGER NOT NULL DEFAULT 0,
    answered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (journey_id, question_key)
);
-- What the player picked, so an answered stop can show their choice next to the right answer.
ALTER TABLE journey_quiz_answer ADD COLUMN IF NOT EXISTS chosen_answer VARCHAR(150);

-- F76 question bank: curated multiple-choice questions per place, managed by administrators.
-- Only ACTIVE questions reach the app; SAMPLE rows come from db/028_seed_place_questions.sql.
CREATE TABLE IF NOT EXISTS place_question (
    question_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id BIGINT NOT NULL REFERENCES place(place_id) ON DELETE CASCADE,
    question VARCHAR(300) NOT NULL,
    option_a VARCHAR(150) NOT NULL,
    option_b VARCHAR(150) NOT NULL,
    option_c VARCHAR(150) NOT NULL,
    option_d VARCHAR(150) NOT NULL,
    -- 0 = A … 3 = D
    answer_index SMALLINT NOT NULL CHECK (answer_index BETWEEN 0 AND 3),
    explanation VARCHAR(400) NOT NULL DEFAULT '',
    difficulty SMALLINT NOT NULL DEFAULT 1 CHECK (difficulty BETWEEN 1 AND 3),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'ACTIVE', 'INACTIVE')),
    source VARCHAR(20) NOT NULL DEFAULT 'ADMIN' CHECK (source IN ('ADMIN', 'SAMPLE')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (place_id, question)
);
CREATE INDEX IF NOT EXISTS place_question_place_idx ON place_question(place_id, status);

-- Quiz rewards keep walking the only way forward: no steps are given. A correct answer earns
-- explorer points, a card piece and quest progress; all stops of a journey correct = "Am hiểu" card.
CREATE TABLE IF NOT EXISTS explorer_point (
    point_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    source VARCHAR(30) NOT NULL,
    ref_key VARCHAR(80) NOT NULL,
    points INTEGER NOT NULL CHECK (points > 0),
    note VARCHAR(200),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, source, ref_key)
);
CREATE TABLE IF NOT EXISTS user_place_mastery (
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    place_id BIGINT NOT NULL REFERENCES place(place_id) ON DELETE CASCADE,
    mastered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, place_id)
);
