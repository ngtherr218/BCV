-- Quest rewards: an item (reward_item_id + reward_quantity) or explorer points (reward_points).
-- First run only: discovery and culture quests switch to points, walking quests keep their items
-- (shoes and tickets help the walk). Later admin edits are never overwritten.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema = current_schema() AND table_name = 'quest' AND column_name = 'reward_points') THEN
        ALTER TABLE quest ADD COLUMN reward_points INTEGER CHECK (reward_points IS NULL OR reward_points > 0);
        UPDATE quest SET reward_points = CASE cycle_type WHEN 'DAILY' THEN 20 ELSE 50 END,
                         reward_item_id = NULL, reward_quantity = NULL
        WHERE condition_type IN ('DISCOVER_PLACE', 'QUIZ_CORRECT');
        UPDATE quest SET reward_points = CASE cycle_type WHEN 'DAILY' THEN 20 ELSE 50 END
        WHERE reward_item_id IS NULL AND reward_points IS NULL;
    END IF;
END $$;

-- F88: private journal (no moderation). Photos are only ever served to their owner.
CREATE TABLE IF NOT EXISTS journal_photo (
    photo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    place_id BIGINT NOT NULL REFERENCES place(place_id) ON DELETE CASCADE,
    caption VARCHAR(300) NOT NULL DEFAULT '',
    mime_type VARCHAR(20) NOT NULL CHECK (mime_type IN ('image/jpeg','image/png','image/webp')),
    photo_data BYTEA NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS journal_photo_owner_idx ON journal_photo(user_id, place_id);
CREATE TABLE IF NOT EXISTS journal_note (
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    place_id BIGINT NOT NULL REFERENCES place(place_id) ON DELETE CASCADE,
    note VARCHAR(1000) NOT NULL DEFAULT '',
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, place_id)
);

