-- Moderation preserves files for administrator review/restoration; remove means unpublish.
ALTER TABLE app_user ADD COLUMN IF NOT EXISTS media_upload_blocked boolean NOT NULL DEFAULT false;
ALTER TABLE community_media ADD COLUMN IF NOT EXISTS first_approved_at timestamptz;
UPDATE community_media SET first_approved_at=COALESCE(reviewed_at,created_at) WHERE status='APPROVED' AND first_approved_at IS NULL;
ALTER TABLE community_media DROP CONSTRAINT IF EXISTS community_media_status_check;
ALTER TABLE community_media ADD CONSTRAINT community_media_status_check CHECK(status IN ('PENDING','APPROVED','REJECTED','FLAGGED','REMOVED','EXPIRED'));
CREATE TABLE IF NOT EXISTS media_report (
 report_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 media_id bigint NOT NULL REFERENCES community_media ON DELETE CASCADE,
 reporter_id bigint NOT NULL REFERENCES app_user,
 reason varchar(500) NOT NULL CHECK(length(trim(reason))>0),
 status varchar(12) NOT NULL DEFAULT 'OPEN' CHECK(status IN ('OPEN','RESOLVED')),
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 resolved_at timestamptz, resolved_by bigint REFERENCES app_user,
 UNIQUE(media_id,reporter_id)
);
CREATE INDEX IF NOT EXISTS media_report_open_idx ON media_report(media_id,status);
